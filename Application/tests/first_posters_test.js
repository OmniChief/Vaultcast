const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync(__dirname+'/../assets/js/app.js','utf8');
const code=src.slice(src.indexOf('  function enhanceFirstPosters(){'),src.indexOf('  // Reuse the same interactive navigation'));
const images=Array.from({length:8},(_,i)=>({url:'/poster/'+i,isConnected:true,listeners:{},getAttribute(){return this.url;},removeAttribute(){this.url=null;},addEventListener(type,fn){this.listeners[type]=fn;}}));
let observer;
const context={document:{getElementById:()=>({querySelectorAll:()=>images})},IntersectionObserver:function(cb){observer={cb,observe(){},unobserve(){}};return observer;}};
vm.createContext(context);vm.runInContext(code,context);context.enhanceFirstPosters();
assert(images.every(x=>!x.src),'no image requests before visibility');
observer.cb(images.slice(0,5).map(target=>({target,isIntersecting:true})));
assert.equal(images.filter(x=>x.src).length,2,'two initial image requests leave room for navigation');
images[2].isConnected=false;images[0].listeners.load();
assert.equal(images[3].src,'/poster/3');assert(!images[2].src,'detached page does not start another request');
