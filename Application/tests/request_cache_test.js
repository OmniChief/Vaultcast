'use strict';
const assert = require('node:assert/strict');
const createCache = require('../assets/js/request-cache.js');
(async function(){
  let now = 0, calls = 0;
  const cache = createCache(() => now);
  const fetcher = async () => ({ok:true, items:[{title:'Original'}], call:++calls});
  const [a,b] = await Promise.all([cache.read('alice:home',fetcher), cache.read('alice:home',fetcher)]);
  assert.equal(calls,1, 'concurrent navigation shares one request');
  a.items[0].title = 'Changed';
  assert.equal(b.items[0].title,'Original', 'consumers cannot mutate each other');
  assert.equal((await cache.read('alice:home',fetcher)).items[0].title,'Original');
  await cache.read('bob:home',fetcher);
  assert.equal(calls,2, 'identities do not share results');
  now = 15001;
  await cache.read('alice:home',fetcher);
  assert.equal(calls,3, 'expired data is fetched again');
  let resolve;
  const late = cache.read('late', () => new Promise(r => {resolve=r;}));
  await Promise.resolve();
  cache.clear();
  resolve({ok:true, items:[]});
  await late;
  await cache.read('late',fetcher);
  assert.equal(calls,4, 'a response from before invalidation cannot repopulate the cache');
  let failures = 0;
  const fail = async () => { failures++; throw Error('offline'); };
  await assert.rejects(cache.read('error',fail));
  await assert.rejects(cache.read('error',fail));
  assert.equal(failures,2, 'failed requests can be retried');
  for(let i=0;i<41;i++) await cache.read('page:'+i,fetcher);
  const before=calls;
  await cache.read('page:0',fetcher);
  assert.equal(calls,before+1, 'old entries are evicted at the memory limit');
  console.log('request cache: all passed');
})().catch(error => {console.error(error); process.exitCode=1;});
